"""Raw capture (replayer.record) -> compact recording (replayer.fmt) + manifest.

- the event clock is the source's own (simulated) clock: wall-clock arrival is mapped through the <plant>/Plant/SimTime
  samples, so an accelerated simulator yields true process times;
- the first event block is a full snapshot (last value of every retained topic, OPC UA node and Modbus block before the window);
- only changes are kept: MQTT points / OPC UA nodes whose value+quality did not change, repeated AGV states and gateway status
  are dropped, Modbus blocks are reduced to the registers that changed; the source heartbeat (<plant>/_status) and the
  clock nodes (Plant/SimTime, SimTimeText, Speed, Paused, TimeMode) are generated by the player instead;
- timestamps become offsets / tokens relative to t0 (see fmt.py), the wall-clock stamps are dropped.
"""
import bisect
import gzip
import json
import logging
import os
import re
from collections import Counter
from datetime import datetime, timezone

from . import pointtable
from .fmt import FORMAT, RE_ISO, RE_LOCAL, STD_KEYS, TOKEN

log = logging.getLogger('replayer.compile')
GENERATED_NODES = ('SimTime', 'SimTimeText', 'Speed', 'Paused', 'TimeMode')
# identifiers that carry the production date (yymmdd) - moved by whole days with the time shift on every loop
ID_PATTERNS = [r'^SH(\d{6})\d{5}$', r'^L(\d{6})-\d+$']


def _epoch(s):
    d = datetime.fromisoformat(s.replace('Z', '+00:00'))
    if d.tzinfo is None:
        d = d.astimezone()
    return d.timestamp()


class Clock:
    """wall arrival -> source time (epoch s), from (wall, SimTime) samples."""

    def __init__(self, pairs):
        pairs.sort()
        self.w = [p[0] for p in pairs]
        self.s = [p[1] for p in pairs]

    def __call__(self, w):
        i = bisect.bisect_left(self.w, w)
        if i <= 0:
            if len(self.w) > 1:
                k = (self.s[1] - self.s[0]) / max(1e-6, self.w[1] - self.w[0])
                return self.s[0] - (self.w[0] - w) * k
            return self.s[0] - (self.w[0] - w)
        if i >= len(self.w):
            k = (self.s[-1] - self.s[-2]) / max(1e-6, self.w[-1] - self.w[-2]) if len(self.w) > 1 else 1
            return self.s[-1] + (w - self.w[-1]) * k
        w0, w1, s0, s1 = self.w[i - 1], self.w[i], self.s[i - 1], self.s[i]
        return s0 + (s1 - s0) * (w - w0) / max(1e-6, w1 - w0)


def compile_raw(a):
    raw = a.raw
    hdr, meta, order = None, None, None
    pairs = []
    # pass 1: header, OPC UA metadata, clock samples
    with gzip.open(raw, 'rt', encoding='utf-8') as f:
        for line in f:
            o = json.loads(line)
            k = o['k']
            if k == 'hdr':
                hdr = o
            elif k == 'meta':
                meta, order = o['opcua'], o['order']
            elif k == 'o' and order and order[o['n']].endswith('/Plant/SimTime') and isinstance(o['v'], dict):
                pairs.append((o['w'], o['v']['$dt']))
    if not pairs:
        raise SystemExit('no <plant>/Plant/SimTime samples in the capture: cannot map arrival times to source time')
    pid = hdr['plant']
    clock = Clock(pairs)
    src_t0 = clock(pairs[0][0]) + a.skip * 60
    t0 = int(src_t0)                                   # whole seconds
    end_ms = int(a.hours * 3600 * 1000)
    tz = datetime.fromtimestamp(t0).astimezone().tzinfo
    t0_dt = datetime.fromtimestamp(t0, tz)
    lo_ok, hi_ok = t0 - 7 * 86400, t0 + a.hours * 3600 + 86400

    def tok(v, key=None):
        """Replace time strings by tokens (recursively)."""
        if isinstance(v, str):
            if key == 'wall_ts' and RE_ISO.match(v):
                return TOKEN + 'W|m'
            if RE_ISO.match(v):
                e = _epoch(v)
                if lo_ok <= e <= hi_ok:
                    return f"{TOKEN}T{int(round((e - t0) * 1000))}|{'m' if '.' in v else 'i'}"
            elif RE_LOCAL.match(v):
                e = datetime.strptime(v, '%Y-%m-%d %H:%M:%S').replace(tzinfo=tz).timestamp()
                if lo_ok <= e <= hi_ok:
                    return f'{TOKEN}T{int(round((e - t0) * 1000))}|s'
            return v
        if isinstance(v, dict):
            if set(v) == {'$dt'}:
                return {'$t': int(round((v['$dt'] - t0) * 1000))}
            return {k2: tok(x, k2) for k2, x in v.items()}
        if isinstance(v, list):
            return [tok(x) for x in v]
        return v

    pkg = pointtable.load(a.package) if a.package else {'points': []}
    blocks = pointtable.modbus_blocks(pkg['points'])

    # pass 2: events -> (rel_ms, seq, kind, data); state before the window -> snapshot
    pre_m, pre_o, pre_b = {}, {}, {}
    evs = []
    seq = 0
    gen_nodes = {i for i, n in enumerate(order or []) if n.rsplit('/', 1)[-1] in GENERATED_NODES and '/Plant/' in n}
    with gzip.open(raw, 'rt', encoding='utf-8') as f:
        for line in f:
            o = json.loads(line)
            k = o['k']
            if k not in ('m', 'o', 'b'):
                continue
            arr = clock(o['w'])
            src = None                                 # the source's own stamp when it is close to the arrival (exact ordering)
            if k == 'm' and o['p'][:1] == '{':
                try:
                    p = json.loads(o['p'])
                    s = p.get('ts') if isinstance(p.get('ts'), str) else p.get('sim_ts') if isinstance(p.get('sim_ts'), str) else None
                    src = _epoch(s) if s and RE_ISO.match(s) else None
                except (ValueError, AttributeError):
                    src = None
            elif k == 'o':
                src = o.get('st')
            if src is not None and abs(src - arr) <= 60:
                arr = src
            rel = int(round((arr - t0) * 1000))
            if rel > end_ms:
                continue
            seq += 1
            if k == 'm':
                t = o['t']
                if t == f'vfactory/{pid}/_status':
                    continue
                if rel < 0:
                    if '/_mes/' not in t and not t.startswith('vda5050/'):
                        pre_m[t] = o
                    continue
                evs.append((rel, seq, 'm', o))
            elif k == 'o':
                if o['n'] in gen_nodes:
                    continue
                if rel < 0:
                    pre_o[o['n']] = o
                    continue
                evs.append((rel, seq, 'o', o))
            else:
                key = (o['u'], o['tb'], o['a'])
                if rel < 0:
                    pre_b[key] = o
                    continue
                evs.append((rel, seq, 'b', o))
    snap = [(0, -3, 'm', o) for o in pre_m.values()] + [(0, -2, 'o', o) for o in pre_o.values()] + [(0, -1, 'b', o) for o in pre_b.values()]
    evs.sort(key=lambda e: (e[0], e[1]))
    evs = snap + evs
    log.info('events in window: %d (+%d snapshot)', len(evs) - len(snap), len(snap))

    topics, tindex, units = [], {}, {}
    nodes = list(order or [])
    last_m, last_o, last_b = {}, {}, {}
    counts = Counter()
    out_lines = []
    prev = 0
    max_rel = 0

    def tid(t):
        i = tindex.get(t)
        if i is None:
            i = tindex[t] = len(topics)
            topics.append(t)
        return i

    def emit(rel, arr):
        nonlocal prev, max_rel
        arr[1] = rel - prev
        prev = rel
        max_rel = max(max_rel, rel)
        out_lines.append(json.dumps(arr, ensure_ascii=False, separators=(',', ':')))

    for rel, _s, kind, o in evs:
        rel = max(0, rel)
        if kind == 'm':
            t, text = o['t'], o['p']
            try:
                p = json.loads(text) if text else None
            except ValueError:
                p = text
            is_mes = '/_mes/' in t
            if not is_mes:
                # change-only (ignoring the time fields) for everything except the MES gateway messages
                sig = json.dumps({k2: v for k2, v in p.items() if k2 not in ('ts', 'sim_ts', 'wall_ts', 'timestamp', 'headerId')}, sort_keys=True,
                                 ensure_ascii=False) if isinstance(p, dict) else text
                if last_m.get(t) == sig:
                    counts['mqtt_dup'] += 1
                    continue
                last_m[t] = sig
            if isinstance(p, dict) and tuple(p.keys()) == STD_KEYS and p['ts'] == p['sim_ts'] and p['quality'] == 'good' \
                    and units.setdefault(t, p['unit']) == p['unit'] and RE_ISO.match(p['ts']):
                ts_rel = int(round((_epoch(p['ts']) - t0) * 1000))
                if '.' in p['ts']:
                    off = ts_rel - rel                 # millisecond stamp (action signals)
                else:
                    off = None if ts_rel == rel else ['s', ts_rel - rel]   # whole seconds; retained values keep their old stamp
                v = tok(p['value'])
                emit(rel, ['P', 0, tid(t), v, off])
                counts['mqtt'] += 1
            else:
                retain = not is_mes and not t.startswith('vda5050/')
                emit(rel, ['M', 0, tid(t), tok(p), retain])
                counts['mqtt'] += 1
                if is_mes:
                    counts['mes_part' if t.endswith('/part') else 'mes_event'] += 1
        elif kind == 'o':
            n = o['n']
            sig = (json.dumps(o['v'], sort_keys=True), o['s'])
            if last_o.get(n) == sig:
                counts['opcua_dup'] += 1
                continue
            last_o[n] = sig
            off = int(round((o['st'] - t0) * 1000)) - rel if o.get('st') else None
            emit(rel, ['O', 0, n, tok(o['v']), off, o['s']])
            counts['opcua'] += 1
        else:
            key = (o['u'], o['tb'], o['a'])
            old = last_b.get(key)
            new = o['r']
            last_b[key] = new
            if old is None or len(old) != len(new):
                emit(rel, ['B', 0, o['u'], o['tb'], o['a'], new])
                counts['modbus'] += 1
                continue
            i = 0
            while i < len(new):                      # changed runs only
                if new[i] == old[i]:
                    i += 1
                    continue
                j = i
                while j < len(new) and (new[j] != old[j] or (j + 1 < len(new) and new[j + 1] != old[j + 1])):
                    j += 1
                emit(rel, ['B', 0, o['u'], o['tb'], o['a'] + i, new[i:j]])
                counts['modbus'] += 1
                i = j

    # OPC UA metadata for the nodes we serve (clock nodes are served too, values generated)
    header = {'format': FORMAT, 'plant': pid, 't0': t0_dt.isoformat(timespec='seconds'), 'duration_ms': max(end_ms if max_rel > end_ms * 0.98 else max_rel, 1),
              'source': a.source, 'created': datetime.now().astimezone().isoformat(timespec='seconds'),
              'topics': topics, 'topic_units': {str(tindex[t]): u for t, u in units.items() if t in tindex}, 'nodes': nodes, 'opcua': meta,
              'modbus': {'blocks': [list(b) for b in blocks]}, 'ids': ID_PATTERNS, 'counts': dict(counts),
              'note': 'Recorded from the de-identified demo foundry of the HoneyMeta plant simulator. All names are fictitious.'}
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with gzip.open(a.out, 'wt', encoding='utf-8', compresslevel=9) as f:
        f.write(json.dumps(header, ensure_ascii=False, separators=(',', ':')) + '\n')
        for ln in out_lines:
            f.write(ln + '\n')
    size = os.path.getsize(a.out)
    manifest = {'plant': pid, 'file': os.path.basename(a.out), 'bytes': size, 'format': FORMAT, 'source': a.source,
                'recorded_from': t0_dt.isoformat(timespec='seconds'), 'duration_h': round(header['duration_ms'] / 3600000, 3),
                'created': header['created'], 'counts': {'mqtt_messages': counts['mqtt'], 'mes_part_events': counts['mes_part'],
                                                         'mes_production_events': counts['mes_event'], 'opcua_value_changes': counts['opcua'],
                                                         'modbus_register_changes': counts['modbus'], 'events_total': len(out_lines),
                                                         'mqtt_topics': len(topics), 'opcua_nodes': len(nodes),
                                                         'modbus_blocks': len(blocks)},
                'dropped_as_unchanged': {'mqtt': counts['mqtt_dup'], 'opcua': counts['opcua_dup']}}
    mpath = re.sub(r'\.jsonl\.gz$', '', a.out) + '.manifest.json'
    with open(mpath, 'w', encoding='utf-8') as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1)
    print(json.dumps(manifest, ensure_ascii=False, indent=1))
