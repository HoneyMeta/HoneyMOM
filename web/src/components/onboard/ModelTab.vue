<template>
  <div class="md" data-test="onboard-model">
    <div class="grid">
      <HmCard :title="$t('modelTab.plantHierarchy')" flush data-tour="model-tree">
        <div class="treebox">
          <el-tree :data="tree" :props="{ label: 'label', children: 'children' }" node-key="key" default-expand-all highlight-current :expand-on-click-node="false" data-test="model-tree"
            @node-click="pick">
            <template #default="{ data: d }">
              <span class="tn"><span class="ty">{{ TYPE_CN[d.type] || '' }}</span><span>{{ d.label }}</span>
                <span v-if="d.type === 'device'" class="pc hm-num">{{ d.confirmed }}/{{ d.points }}</span></span>
            </template>
          </el-tree>
        </div>
      </HmCard>

      <div class="right">
        <HmCard v-if="dev" :title="`${dev.device.code} ${dev.device.name}`" data-test="model-device">
          <template #actions><el-button link size="small" @click="router.push('/e/equipment?id=' + dev.device.id)">{{ $t('modelTab.register') }}</el-button></template>
          <div class="facts">
            <span>{{ $t('common.type') }} <b>{{ dev.template?.name || dev.device.etype }}</b></span><span>{{ $t('modelTab.model0', [dev.device.model || '—']) }}</span>
            <span>{{ $t('common.position') }} <span class="hm-num">{{ dev.device.x ?? '—' }}, {{ dev.device.y ?? '—' }}</span> {{ $t('modelTab.mHeading0', [dev.device.rot ?? 0]) }}</span>
            <span>{{ $t('modelTab.size') }} <span class="hm-num">{{ dev.device.w ?? '—' }} × {{ dev.device.d ?? '—' }}</span> m</span><span>{{ $t('modelTab.idealCycleTime0S', [dev.device.ideal_cycle_s ?? '—']) }}</span>
            <span>{{ $t('modelTab.n3d0', [dev.device.model3d || $t('modelTab.autoGeneratedFromTemplate')]) }}</span>
          </div>
          <HmDataTable :columns="P_COLS" :rows="dev.points" row-key="id" :ai="false" :max-height="380">
            <template #cell-role="{ row }">{{ ROLE_CN[row.role] || row.role || '—' }}</template>
            <template #cell-latest="{ row }"><span class="hm-num">{{ row.latest ? fmtV(row.latest.value ?? row.latest.text) : '—' }}</span> <span class="muted small">{{ row.unit || '' }}</span></template>
            <template #cell-status="{ row }"><HmTag :tone="row.status === 'confirmed' ? 'ok' : 'warn'">{{ STATUS_CN[row.status] || $t('common.toConfirm') }}</HmTag></template>
          </HmDataTable>
        </HmCard>

        <HmCard :title="$t('common.equipmentTypeTemplates')" flush data-tour="model-templates">
          <HmDataTable :columns="T_COLS" :rows="tpls" row-key="code" :ai="false" :max-height="320" data-test="templates-table">
            <template #cell-builtin="{ row }"><HmTag :tone="row.builtin ? 'neutral' : 'primary'">{{ row.builtin ? $t('common.builtIn') : $t('modelTab.custom') }}</HmTag></template>
            <template #cell-op="{ row }"><el-button v-perm="'factory.template.apply'" link size="small" type="primary" :data-test="'tpl-apply-' + row.code" @click="openApply(row)">{{ $t('modelTab.applyInBulk') }}</el-button></template>
          </HmDataTable>
        </HmCard>

        <HmCard :title="$t('modelTab.modelVersions')" data-tour="model-versions">
          <template #actions>
            <el-input v-model="note" size="small" :placeholder="$t('modelTab.versionNotes')" class="note" />
            <el-button v-perm="'factory.model.publish'" size="small" type="primary" data-test="publish" @click="publish">{{ $t('modelTab.publishNewVersion') }}</el-button>
          </template>
          <div class="vers">
            <div v-for="v in versions" :key="v.version" class="ver">
              <b>V{{ v.version }}</b><span class="hm-mono small">{{ v.published_at }}</span><span class="small">{{ v.published_by }}</span><span class="small grow">{{ v.note }}</span>
              <span class="small muted">{{ $t('modelTab.n0Machines1Tags', [v.counts?.devices, v.counts?.points]) }}</span>
              <el-button link size="small" type="primary" :data-test="'diff-' + v.version" @click="showDiff(v.version)">{{ $t('modelTab.compareWithCurrent') }}</el-button>
            </div>
            <div v-if="!versions.length" class="muted small">{{ $t('modelTab.noVersionsPublishedYet') }}</div>
          </div>
          <div v-if="diff" class="diff" data-test="version-diff">
            <div class="dh">{{ $t('modelTab.v01', [diff.a, diff.b === 'current' ? $t('modelTab.current') : 'V' + diff.b]) }}<span v-for="(n, k) in diff.total" :key="k" class="small">{{ $t('modelTab.n01', [GRP_CN[k], n]) }}</span></div>
            <template v-for="(g, k) in diff.diff" :key="k">
              <div v-if="g.added.length || g.removed.length || g.changed.length" class="dg">
                <b>{{ GRP_CN[k] }}</b>
                <span v-if="g.added.length" class="add">{{ $t('modelTab.added01', [g.added.slice(0, 12).join($t('common.k42')), g.added.length > 12 ? $t('modelTab.and0More', [g.added.length]) : '']) }}</span>
                <span v-if="g.removed.length" class="rem">{{ $t('modelTab.deleted01', [g.removed.slice(0, 12).join($t('common.k42')), g.removed.length > 12 ? $t('modelTab.and0More', [g.removed.length]) : '']) }}</span>
                <div v-for="c in g.changed.slice(0, 20)" :key="c.key" class="chg"><span class="hm-mono">{{ c.key }}</span>{{ $t('common.k384') }}<span v-for="(v, f) in c.fields" :key="f">{{ $t('modelTab.n012', [f, fmtV(v[0]), fmtV(v[1])]) }}</span></div>
              </div>
            </template>
          </div>
        </HmCard>
      </div>
    </div>

    <el-dialog v-model="adlg" :title="$t('modelTab.applyTemplateInBulk0', [cur?.name || ''])" width="560px" append-to-body data-test="apply-dialog">
      <p class="small muted">{{ $t('modelTab.afterApplyingEquipmentTypeDefault') }}</p>
      <el-form label-width="96px" size="small">
        <el-form-item :label="$t('common.equipment')"><el-select v-model="form.devices" multiple filterable style="width:100%" data-test="apply-devices"><el-option v-for="d in devices" :key="d.code" :label="$t('modelTab.n0122', [d.code, d.name, d.model || '—'])" :value="d.code" /></el-select></el-form-item>
        <el-form-item :label="$t('modelTab.sameModel')"><el-select v-model="form.model" clearable filterable style="width:100%"><el-option v-for="m in models" :key="m" :label="m" :value="m" /></el-select></el-form-item>
        <el-form-item :label="$t('modelTab.addStandardTags')"><el-switch v-model="form.create_points" /></el-form-item>
        <el-form-item v-if="form.create_points" :label="$t('common.dataSource')"><el-select v-model="form.datasource" style="width:100%"><el-option v-for="s in sources" :key="s.id" :label="s.code" :value="s.id" /></el-select></el-form-item>
      </el-form>
      <template #footer><el-button @click="adlg = false">{{ $t('common.cancel') }}</el-button><el-button type="primary" :disabled="!form.devices?.length && !form.model" data-test="apply-ok" @click="apply">{{ $t('modelTab.apply') }}</el-button></template>
    </el-dialog>
  </div>
</template>

<script setup lang="ts">
import { $t } from '../../i18n';
import { ElMessage } from 'element-plus';
import { computed, onMounted, ref } from 'vue';
import { useRouter } from 'vue-router';
import { get, post } from '../../api';
import { ROLE_CN, STATUS_CN } from './common';

const router = useRouter();
const tree = ref<any[]>([]), dev = ref<any>(null), tpls = ref<any[]>([]), versions = ref<any[]>([]), diff = ref<any>(null), note = ref(''), devices = ref<any[]>([]), sources = ref<any[]>([]);
const TYPE_CN: Record<string, string> = { plant: $t('common.plant'), workshop: $t('common.workshop'), line: $t('common.line'), device: $t('common.equipment'), group: '' };
const GRP_CN: Record<string, string> = { workshops: $t('common.workshop'), lines: $t('common.line'), stations: $t('common.workstation'), devices: $t('common.equipment'), datasources: $t('common.dataSource'), points: $t('common.tag') };
const P_COLS = [{ key: 'code', label: $t('common.tagCode') }, { key: 'desc', label: $t('common.meaning') }, { key: 'role', label: $t('common.purpose'), width: 76 }, { key: 'latest', label: $t('modelTab.latestValue'), width: 130, sortable: false },
  { key: 'protocol', label: $t('common.protocol'), width: 64 }, { key: 'status', label: $t('common.confirm'), width: 70 }];
const T_COLS = [{ key: 'code', label: $t('common.code'), width: 100 }, { key: 'name', label: $t('common.equipmentType'), width: 120 }, { key: 'category', label: $t('modelTab.class'), width: 70 }, { key: 'aliases', label: $t('modelTab.alias') },
  { key: 'n_points', label: $t('common.tag'), num: true, width: 56 }, { key: 'devices', label: $t('common.equipment'), num: true, width: 56 }, { key: 'builtin', label: '', width: 64 }, { key: 'op', label: '', width: 80, sortable: false }];
const fmtV = (v: any) => (v === null || v === undefined || v === '' ? '—' : typeof v === 'number' && !Number.isInteger(v) ? v.toFixed(3) : typeof v === 'object' ? JSON.stringify(v) : String(v));
const models = computed(() => [...new Set(devices.value.map((d) => d.model).filter(Boolean))]);

function label(n: any): any {
  return { ...n, key: n.type + ':' + n.id, label: n.type === 'device' ? `${n.code} ${n.name}` : n.name, children: (n.children || []).map(label) };
}
async function load() {
  tree.value = (await get('/api/factory/tree')).tree.map(label);
  tpls.value = (await get('/api/factory/templates')).items;
  versions.value = (await get('/api/factory/versions')).versions;
  devices.value = (await get('/api/factory/devices')).items;
}
async function pick(n: any) { if (n.type === 'device') dev.value = await get('/api/factory/device/' + encodeURIComponent(n.code)); }
async function publish() { const r = await post('/api/factory/versions', { note: note.value }); ElMessage.success($t('modelTab.publishedV0', [r.version])); note.value = ''; load(); }
async function showDiff(v: number) { diff.value = await get(`/api/factory/versions/diff?a=${v}&b=current`); }
const adlg = ref(false), cur = ref<any>(null), form = ref<any>({});
async function openApply(t: any) {
  cur.value = t; form.value = { devices: devices.value.filter((d) => d.template === t.code).map((d) => d.code), model: '', create_points: false, datasource: null };
  sources.value = (await get('/api/onboard/summary', true).catch(() => null))?.sources || [];
  adlg.value = true;
}
async function apply() {
  const r = await post(`/api/factory/templates/${cur.value.code}/apply`, form.value);
  ElMessage.success($t('modelTab.appliedTo0Machines1', [r.devices, r.points_updated, r.points_created]));
  adlg.value = false; load();
}
onMounted(load);
</script>

